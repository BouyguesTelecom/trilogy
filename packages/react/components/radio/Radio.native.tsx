import { ComponentName } from '@/components/enumsComponentsName'
import { RadioNativeProps, RadioNativeRef } from '@/components/radio/RadioProps'
import { Text } from '@/components/text'
import { getColorStyle, TrilogyColor } from '@/objects/facets/Color'
import { forwardRef, Ref, useId } from 'react'
import { View } from 'react-native'
import { memoStyles } from '@/helpers/memoStyles'
import { useAnimatedPressable } from '@/hooks/useAnimatedPressable'
import { AnimatedPressable } from '@/components/animatedPressable/AinmatedPressable.native'

/**
 * Radio Component
 * @param checked {boolean} Checked radio
 * @param disabled {boolean} Disabled radio
 * @param readonly {boolean} Readonly radio
 * @param id {string} Radio id (auto-generated by default)
 * @param label {string} Label for radio
 * @param onChange {RadioChangeEventHandlerNative} onChange Event
 * @param name {string} Name for radio
 * @param value {string} Value for radio
 */
const Radio = forwardRef<RadioNativeRef, RadioNativeProps>(
  ({ id = useId(), checked, name, onChange, disabled, readonly, label, value }, ref): JSX.Element => {
    const { animatedStyle, handleAnimate } = useAnimatedPressable()
    const styles = memoStyles({
      container: {
        flexDirection: 'row',
        alignItems: 'center',
      },
      radio: {
        alignItems: 'center',
        justifyContent: 'center',
        borderColor: getColorStyle(
          disabled ? TrilogyColor.DISABLED : checked ? TrilogyColor.MAIN : TrilogyColor.STROKE,
        ),
        borderWidth: 1,
        width: 18,
        height: 18,
        borderRadius: 10,
        marginRight: 10,
      },
      icon: {
        borderRadius: 12,
        width: 12,
        height: 12,
        backgroundColor: getColorStyle(TrilogyColor.MAIN),
      },
      label: {
        paddingTop: 2,
        color:
          (disabled && getColorStyle(TrilogyColor.DISABLED)) ||
          (checked && getColorStyle(TrilogyColor.MAIN)) ||
          getColorStyle(TrilogyColor.MAIN),
      },
    })

    const handleClick = (value: string) => {
      if (!readonly) {
        if (onChange) {
          onChange({
            radioId: id,
            radioValue: value,
            radioName: name || '',
            radioChecked: true,
          })
        }
      }
    }

    return (
      <AnimatedPressable
        ref={ref as Ref<View>}
        disabled={disabled}
        style={[styles.container, animatedStyle]}
        onPress={() => {
          handleAnimate()
          handleClick(value ?? '')
        }}
      >
        <View style={styles.radio} testID={id}>
          {checked && <View style={styles.icon} />}
        </View>
        {label && typeof label.valueOf() === 'string' ? <Text style={styles.label}>{String(label)}</Text> : label}
      </AnimatedPressable>
    )
  },
)

Radio.displayName = ComponentName.Radio

export default Radio
