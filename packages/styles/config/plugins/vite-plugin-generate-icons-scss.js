import fs from 'fs'
import path from 'path'

export const generateIconsScss = (options) => {
  return {
    name: 'generate-icons-scss',
    order: 'pre',
    configResolved: () => {
      const scssOutputPath = options.scssOutputPath
      const iconsDir = options.iconsDir
      const iconNames = fs
        .readdirSync(iconsDir)
        .filter((fileName) => fileName.endsWith('.svg'))
        .map((fileName) => path.basename(fileName, '.svg'))

      // `--icon-*` is already used by color tokens, hence the `icon-image` namespace.
      const variableName = (iconName) => `icon-image-${iconName}`

      const scssVariables = iconNames
        .map(
          (iconName) =>
            `$${variableName(iconName)}: url('./assets/icons/${options.directory}/${iconName}.svg') !default;`,
        )
        .join('\n')

      const cssVariables = [
        ':root {',
        ...iconNames.map((iconName) => `  --${variableName(iconName)}: #{$${variableName(iconName)}};`),
        '}',
      ].join('\n')

      const iconRules = iconNames
        .map((iconName) => {
          return `.icon .tri-${options.prefix}${iconName} ${options.prefix ? `, icon .tri-${iconName}` : ''} {${
            options.sizeAuto
              ? `  -webkit-mask-size: auto !important;
  mask-size: auto !important;`
              : ''
          }
  -webkit-mask-image: var(--${variableName(iconName)});
  mask-image: var(--${variableName(iconName)});
}`
        })
        .join('\n\n')

      const iconScss = [
        '// Generated by vite-plugin-generate-icons-scss. Do not edit directly.',
        scssVariables,
        cssVariables,
        iconRules,
        '',
      ].join('\n\n')

      fs.writeFileSync(scssOutputPath, iconScss)
    },
  }
}
