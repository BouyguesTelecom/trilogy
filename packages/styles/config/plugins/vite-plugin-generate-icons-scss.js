import fs from 'fs'
import path from 'path'

export const generateIconsScss = (options) => {
  return {
    name: 'generate-icons-scss',
    order: 'pre',
    configResolved: () => {
      const { scssOutputPath, variablesOutputPath, iconsDir, prefix = '', sizeAuto, directory } = options
      const iconNames = fs
        .readdirSync(iconsDir)
        .filter((fileName) => fileName.endsWith('.svg'))
        .map((fileName) => path.basename(fileName, '.svg'))

      // `--icon-*` is already used by color tokens, hence the `icon-image` namespace.
      const variableName = (iconName) => `--icon-image-${iconName}`

      const iconVariables = [
        '// Generated by vite-plugin-generate-icons-scss. Do not edit directly.',
        '// Override or add `--icon-image-<name>` in :root to customize icons.',
        '',
        ':root {',
        ...iconNames.map(
          (iconName) => `  ${variableName(iconName)}: url('./assets/icons/${directory}/${iconName}.svg');`,
        ),
        '}',
        '',
      ].join('\n')

      // Lets plain HTML `<i class="tri-*">` resolve its image; the React Icon sets `--icon-image` inline.
      const iconRules = iconNames
        .map((iconName) => {
          const selectors = [`.icon .tri-${prefix}${iconName}`, prefix && `.icon .tri-${iconName}`]
            .filter(Boolean)
            .join(', ')
          const size = sizeAuto ? '\n  -webkit-mask-size: auto !important;\n  mask-size: auto !important;' : ''
          return `${selectors} {\n  --icon-image: var(${variableName(iconName)});${size}\n}`
        })
        .join('\n\n')

      fs.writeFileSync(variablesOutputPath, iconVariables)
      fs.writeFileSync(
        scssOutputPath,
        ['// Generated by vite-plugin-generate-icons-scss. Do not edit directly.', iconRules, ''].join('\n\n'),
      )
    },
  }
}
